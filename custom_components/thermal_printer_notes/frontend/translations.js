export function detectLanguage(hass = undefined) {
  const requested = hass?.locale?.language
    || hass?.language
    || globalThis.document?.documentElement?.lang
    || globalThis.navigator?.language
    || "en";
  const language = String(requested).toLowerCase().split("-")[0];
  return Object.hasOwn(TRANSLATIONS, language) ? language : "en";
}

export function translate(language, key, replacements = {}) {
  const catalog = TRANSLATIONS[language] || TRANSLATIONS.en;
  const template = catalog[key] ?? TRANSLATIONS.en[key] ?? key;
  return template.replace(/\{([a-z_]+)\}/gi, (_match, name) =>
    Object.hasOwn(replacements, name) ? String(replacements[name]) : `{${name}}`
  );
}
